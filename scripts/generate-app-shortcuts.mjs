#!/usr/bin/env node
/**
 * Generate an AppShortcutsProvider Swift file from JSON config.
 *
 * Usage:
 *   node scripts/generate-app-shortcuts.mjs --config app-shortcuts.config.json --output ios/App/App/CapgoGeneratedAppShortcuts.swift
 */
import fs from 'node:fs';
import path from 'node:path';

function parseArgs(argv) {
  const args = { config: 'app-shortcuts.config.json', output: null };
  for (let i = 2; i < argv.length; i++) {
    const token = argv[i];
    if (token === '--config' && argv[i + 1]) {
      args.config = argv[++i];
    } else if (token === '--output' && argv[i + 1]) {
      args.output = argv[++i];
    } else if (token === '--help' || token === '-h') {
      args.help = true;
    }
  }
  return args;
}

function escapeSwiftString(value) {
  return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

function phraseToSwiftLiteral(phrase) {
  const withAppName = phrase.replace(/\{\{applicationName\}\}/g, '\\(.applicationName)');
  return `"${withAppName.replace(/"/g, '\\"')}"`;
}

function validateConfig(config) {
  if (!config || !Array.isArray(config.shortcuts) || config.shortcuts.length === 0) {
    throw new Error('config.shortcuts must be a non-empty array');
  }
  for (const shortcut of config.shortcuts) {
    if (!shortcut.actionName || !shortcut.shortTitle) {
      throw new Error('Each shortcut needs actionName and shortTitle');
    }
    if (!Array.isArray(shortcut.phrases) || shortcut.phrases.length === 0) {
      throw new Error(`Shortcut ${shortcut.actionName} needs at least one phrase`);
    }
  }
}

function generateSwift(config) {
  const providerName = config.providerName ?? 'CapgoGeneratedAppShortcuts';
  const blocks = config.shortcuts
    .map((shortcut) => {
      const phrases = shortcut.phrases.map((p) => `          ${phraseToSwiftLiteral(p)},`).join('\n');
      const image = escapeSwiftString(shortcut.systemImageName ?? 'bolt');
      const title = escapeSwiftString(shortcut.shortTitle);
      const action = escapeSwiftString(shortcut.actionName);
      return `      AppShortcut(
        intent: CapgoDispatchAppIntent(actionName: "${action}"),
        phrases: [
${phrases}
        ],
        shortTitle: "${title}",
        systemImageName: "${image}"
      ),`;
    })
    .join('\n');

  return `// Generated by @capgo/capacitor-app-intents. Do not edit.
#if canImport(AppIntents)
import AppIntents
import CapgoCapacitorAppIntents

@available(iOS 16.0, *)
struct ${providerName}: AppShortcutsProvider {
  static var appShortcuts: [AppShortcut] {
    [
${blocks}
    ]
  }
}
#endif
`;
}

const args = parseArgs(process.argv);
if (args.help) {
  console.log(`Usage: node scripts/generate-app-shortcuts.mjs --config <file> --output <file.swift>`);
  process.exit(0);
}

const configPath = path.resolve(process.cwd(), args.config);
const outputPath = path.resolve(process.cwd(), args.output ?? 'CapgoGeneratedAppShortcuts.swift');

const config = JSON.parse(fs.readFileSync(configPath, 'utf8'));
validateConfig(config);
const swift = generateSwift(config);
fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, swift, 'utf8');
console.log(`Wrote ${outputPath}`);
