#!/usr/bin/env node
/**
 * Generate typed AppIntent Swift sources from app-intents.codegen JSON.
 *
 * Usage:
 *   node scripts/generate-typed-intents.mjs --config app-intents.codegen.example.json --output-dir ios/App/App/GeneratedAppIntents
 */
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import {
  codegenMinimumIOSVersion,
  collectParamsFromParameters,
  escapeSwiftString,
  loadCodegenConfig,
  parameterPropertyBlock,
  phraseToSwiftLiteral,
  validateSwiftStructName,
} from './capgo-intent-codegen-lib.mjs';

function parseArgs(argv) {
  const args = { config: 'app-intents.codegen.example.json', outputDir: null };
  for (let i = 2; i < argv.length; i++) {
    const token = argv[i];
    if (token === '--config' && argv[i + 1]) {
      args.config = argv[++i];
    } else if (token === '--output-dir' && argv[i + 1]) {
      args.outputDir = argv[++i];
    } else if (token === '--help' || token === '-h') {
      args.help = true;
    }
  }
  return args;
}

function toolMacroLine(intent) {
  if (intent.tool !== true) {
    return '';
  }
  return '\n// Promote to a Siri tool on iOS 27.3+ by adding @AppIntent(.tool) when your SDK supports ToolIntent.\n';
}

function swiftPluginImportModule(config) {
  const name = config.swiftPluginModule ?? 'CapgoCapacitorAppIntents';
  return String(name).replace(/[^A-Za-z0-9_]/g, '_');
}

function generateIntentSwift(intent, config) {
  const parameters = intent.parameters ?? [];
  const title = escapeSwiftString(intent.title);
  const description = escapeSwiftString(intent.description ?? intent.title);
  const systemImage = escapeSwiftString(intent.systemImageName ?? 'bolt');
  const awaits = intent.awaitJavaScriptResult === true;
  const foregroundOnly = intent.foregroundOnly !== false;
  const timeout = intent.timeoutSeconds ?? config.defaultInvocationTimeoutSeconds ?? 30;
  const execution = intent.execution === 'native' ? 'native' : 'javascript';
  const preferNative = execution === 'native';

  const summary =
    parameters.length > 0
      ? `        Summary {\n${parameters.map((p) => `            \\.${'$' + p.name}`).join('\n')}\n        }`
      : `        Summary("${title}")`;

  const paramCollect = collectParamsFromParameters(parameters);

  const availability = awaits ? '@available(iOS 17.0, *)' : '@available(iOS 16.0, *)';

  const performBody = awaits
    ? `    @MainActor
    public func perform() async throws -> some ReturnsValue<String> {
        var params: [String: Any] = [:]
${paramCollect ? `${paramCollect}\n` : ''}
        let options = CapgoIntentPerformOptions(
            actionName: "${escapeSwiftString(intent.actionName)}",
            params: params,
            awaitsJavaScriptResult: true,
            foregroundOnly: ${foregroundOnly},
            timeoutSeconds: TimeInterval(${timeout}),
            preferNativeHandler: ${preferNative}
        )
        return try await CapgoIntentResultSupport.performReturningValue(options: options)
    }`
    : `    @MainActor
    public func perform() async throws -> some IntentResult {
        var params: [String: Any] = [:]
${paramCollect ? `${paramCollect}\n` : ''}
        let options = CapgoIntentPerformOptions(
            actionName: "${escapeSwiftString(intent.actionName)}",
            params: params,
            awaitsJavaScriptResult: false,
            foregroundOnly: ${foregroundOnly},
            timeoutSeconds: TimeInterval(${timeout}),
            preferNativeHandler: ${preferNative}
        )
        return try await CapgoIntentResultSupport.perform(options: options)
    }`;

  return `// Generated by @capgo/capacitor-app-intents. Do not edit.
#if canImport(AppIntents)
import AppIntents
import ${swiftPluginImportModule(config)}
${toolMacroLine(intent)}
${availability}
public struct ${intent.name}: AppIntent {
    public static var title: LocalizedStringResource = "${title}"
    public static var description = IntentDescription("${description}")
    public static var openAppWhenRun: Bool = ${foregroundOnly ? 'true' : 'false'}

${parameterPropertyBlock(parameters)}

    public init() {}

    public static var parameterSummary: some ParameterSummary {
${summary}
    }

${performBody}
}
#endif
`;
}

function shortcutIntentReference(shortcut, intentsByName) {
  if (shortcut.intent && shortcut.intent !== 'CapgoDispatchAppIntent') {
    return `${shortcut.intent}()`;
  }
  const action = escapeSwiftString(shortcut.actionName);
  return `CapgoDispatchAppIntent(actionName: "${action}")`;
}

function intentByName(config, name) {
  return (config.intents ?? []).find((intent) => intent.name === name);
}

function shortcutRequiresIOS17(shortcut, config) {
  if (shortcut.intent && shortcut.intent !== 'CapgoDispatchAppIntent') {
    return intentByName(config, shortcut.intent)?.awaitJavaScriptResult === true;
  }
  return false;
}

function appShortcutBlock(shortcut) {
  const phrases = shortcut.phrases.map((p) => `        ${phraseToSwiftLiteral(p)},`).join('\n');
  const image = escapeSwiftString(shortcut.systemImageName ?? 'bolt');
  const title = escapeSwiftString(shortcut.shortTitle);
  const intentRef = shortcutIntentReference(shortcut, new Map());
  return `    AppShortcut(
      intent: ${intentRef},
      phrases: [
${phrases}
      ],
      shortTitle: "${title}",
      systemImageName: "${image}"
    )`;
}

function generateShortcutsProvider(config) {
  const pluginModule = swiftPluginImportModule(config);
  const providerName = config.providerName ?? 'CapgoGeneratedAppShortcuts';
  const shortcuts = config.shortcuts ?? [];
  const ios16Shortcuts = shortcuts.filter((shortcut) => !shortcutRequiresIOS17(shortcut, config));
  const ios17Shortcuts = shortcuts.filter((shortcut) => shortcutRequiresIOS17(shortcut, config));

  const ios16Blocks = ios16Shortcuts.map(appShortcutBlock).join('\n');
  const ios17Blocks = ios17Shortcuts.map(appShortcutBlock).join('\n');
  const allBlocks = shortcuts.map(appShortcutBlock).join('\n');

  const minimumIOS = codegenMinimumIOSVersion(config);
  const emitIos17Provider = minimumIOS >= 17;
  const hasMixedAvailability =
    !emitIos17Provider && ios16Shortcuts.length > 0 && ios17Shortcuts.length > 0;

  const builderBody = emitIos17Provider
    ? allBlocks || '    // no shortcuts'
    : hasMixedAvailability
      ? ios16Blocks
      : allBlocks || '    // no shortcuts';

  const omittedTitles = ios17Shortcuts.map((s) => s.shortTitle);
  const mixedNote = hasMixedAvailability
    ? `// Tool Siri phrases for ${omittedTitles.join(', ')} are omitted from this AppShortcutsProvider (iOS 17+ typed shortcuts in a mixed config).
// Apple allows one AppShortcutsProvider per app, and Xcode 26 rejects if #available inside @AppShortcutsBuilder.
// Typed tool intents are still generated as AppIntent types for iOS 17 Shortcuts/Siri discovery.
// Set "minimumIOSVersion": 17 in app-intents.codegen.json to emit all shortcuts on one @available(iOS 17.0, *) provider, or add a CapgoDispatchAppIntent shortcut for the phrase.
#warning("Capgo codegen omitted App Shortcut Siri phrases for: ${omittedTitles.join(', ')}. Set minimumIOSVersion to 17 in app-intents.codegen.json or see @capgo/capacitor-app-intents README.")
`
    : '';

  const providerAvailability = emitIos17Provider
    ? '@available(iOS 17.0, *)'
    : ios16Shortcuts.length > 0
      ? '@available(iOS 16.0, *)'
      : ios17Shortcuts.length > 0
        ? '@available(iOS 17.0, *)'
        : '@available(iOS 16.0, *)';

  return `// Generated by @capgo/capacitor-app-intents. Do not edit.
#if canImport(AppIntents)
import AppIntents
import ${pluginModule}

${mixedNote}${providerAvailability}
struct ${providerName}: AppShortcutsProvider {
  @AppShortcutsBuilder
  static var appShortcuts: [AppShortcut] {
${builderBody}
  }
}
#endif
`;
}

export function describeMixedShortcutOmissions(config) {
  if (codegenMinimumIOSVersion(config) >= 17) {
    return null;
  }
  const shortcuts = config.shortcuts ?? [];
  const ios17Shortcuts = shortcuts.filter((shortcut) => shortcutRequiresIOS17(shortcut, config));
  const ios16Shortcuts = shortcuts.filter((shortcut) => !shortcutRequiresIOS17(shortcut, config));
  if (ios16Shortcuts.length === 0 || ios17Shortcuts.length === 0) {
    return null;
  }
  const titles = ios17Shortcuts.map((s) => s.shortTitle).join(', ');
  return {
    omittedShortTitles: ios17Shortcuts.map((s) => s.shortTitle),
    cliMessage:
      `Capgo codegen: omitting App Shortcut Siri phrases for [${titles}] ` +
      '(iOS 17 typed intents in a mixed config with iOS 16 dispatch shortcuts). ' +
      'Apple allows one AppShortcutsProvider; Xcode 26 rejects #available inside @AppShortcutsBuilder. ' +
      'Set minimumIOSVersion to 17 in app-intents.codegen.json to register all phrases, or use a CapgoDispatchAppIntent shortcut for the phrase. ' +
      'See @capgo/capacitor-app-intents README.',
  };
}

export function generateShortcutsProviderSwift(config) {
  return generateShortcutsProvider(config);
}

const isMain = import.meta.url === pathToFileURL(process.argv[1] ?? '').href;

if (isMain) {
const args = parseArgs(process.argv);
if (args.help) {
  console.log(
    'Usage: node scripts/generate-typed-intents.mjs --config <file> --output-dir <dir>',
  );
  process.exit(0);
}

const configPath = path.resolve(process.cwd(), args.config);
const outputDir = path.resolve(
  process.cwd(),
  args.outputDir ?? 'CapgoGeneratedAppIntents',
);

const config = loadCodegenConfig(configPath);
fs.mkdirSync(outputDir, { recursive: true });

const expectedFiles = new Set();
for (const intent of config.intents ?? []) {
  validateSwiftStructName(intent.name, 'intent.name');
  const file = path.join(outputDir, `${intent.name}.swift`);
  expectedFiles.add(`${intent.name}.swift`);
  fs.writeFileSync(file, generateIntentSwift(intent, config), 'utf8');
  console.log(`Wrote ${file}`);
}

if (Array.isArray(config.shortcuts) && config.shortcuts.length > 0) {
  const mixedOmission = describeMixedShortcutOmissions(config);
  if (mixedOmission) {
    console.warn(`warning: ${mixedOmission.cliMessage}`);
  }
  const providerFile = `${config.providerName ?? 'CapgoGeneratedAppShortcuts'}.swift`;
  expectedFiles.add(providerFile);
  const shortcutsFile = path.join(outputDir, providerFile);
  fs.writeFileSync(shortcutsFile, generateShortcutsProvider(config), 'utf8');
  console.log(`Wrote ${shortcutsFile}`);
}

if (fs.existsSync(outputDir)) {
  for (const entry of fs.readdirSync(outputDir)) {
    if (entry.endsWith('.swift') && !expectedFiles.has(entry)) {
      fs.unlinkSync(path.join(outputDir, entry));
      console.log(`Removed obsolete ${entry}`);
    }
  }
}
}
