#!/usr/bin/env node
/**
 * Generate typed AppIntent Swift sources from app-intents.codegen JSON.
 *
 * Usage:
 *   node scripts/generate-typed-intents.mjs --config app-intents.codegen.example.json --output-dir ios/App/App/GeneratedAppIntents
 */
import fs from 'node:fs';
import path from 'node:path';
import {
  collectParamsFromParameters,
  escapeSwiftString,
  loadCodegenConfig,
  parameterPropertyBlock,
  parameterSummaryArgs,
  phraseToSwiftLiteral,
} from './capgo-intent-codegen-lib.mjs';

function parseArgs(argv) {
  const args = { config: 'app-intents.codegen.example.json', outputDir: null };
  for (let i = 2; i < argv.length; i++) {
    const token = argv[i];
    if (token === '--config' && argv[i + 1]) {
      args.config = argv[++i];
    } else if (token === '--output-dir' && argv[i + 1]) {
      args.outputDir = argv[++i];
    } else if (token === '--help' || token === '-h') {
      args.help = true;
    }
  }
  return args;
}

function toolMacroLine(intent) {
  if (intent.tool !== true) {
    return '';
  }
  return '\n// Promote to a Siri tool on iOS 27.3+ by adding @AppIntent(.tool) when your SDK supports ToolIntent.\n';
}

function generateIntentSwift(intent) {
  const parameters = intent.parameters ?? [];
  const title = escapeSwiftString(intent.title);
  const description = escapeSwiftString(intent.description ?? intent.title);
  const systemImage = escapeSwiftString(intent.systemImageName ?? 'bolt');
  const awaits = intent.awaitJavaScriptResult === true;
  const foregroundOnly = intent.foregroundOnly !== false;
  const timeout = intent.timeoutSeconds ?? 30;
  const execution = intent.execution === 'native' ? 'native' : 'javascript';
  const preferNative = execution === 'native';

  const summaryArgs = parameterSummaryArgs(parameters);
  const summary =
    summaryArgs.length > 0
      ? `        Summary("${title} ${summaryArgs}")`
      : `        Summary("${title}")`;

  const paramCollect = collectParamsFromParameters(parameters);

  return `// Generated by @capgo/capacitor-app-intents. Do not edit.
#if canImport(AppIntents)
import AppIntents
import CapgoCapacitorAppIntents
${toolMacroLine(intent)}
@available(iOS 16.0, *)
public struct ${intent.name}: AppIntent {
    public static var title: LocalizedStringResource = "${title}"
    public static var description = IntentDescription("${description}")
    public static var openAppWhenRun: Bool = ${foregroundOnly ? 'true' : 'false'}

${parameterPropertyBlock(parameters)}

    public init() {}

    public static var parameterSummary: some ParameterSummary {
${summary}
    }

    @MainActor
    public func perform() async throws -> some IntentResult {
        var params: [String: Any] = [:]
${paramCollect ? `${paramCollect}\n` : ''}
        let options = CapgoIntentPerformOptions(
            actionName: "${escapeSwiftString(intent.actionName)}",
            params: params,
            awaitsJavaScriptResult: ${awaits},
            foregroundOnly: ${foregroundOnly},
            timeoutSeconds: TimeInterval(${timeout}),
            preferNativeHandler: ${preferNative}
        )

        if ${awaits} {
            if #available(iOS 17.0, *) {
                return try await CapgoIntentResultSupport.performReturningValue(options: options)
            }
            return try await CapgoIntentResultSupport.performReturningString(options: options)
        }

        return try await CapgoIntentResultSupport.fireAndForget(perform: options)
    }
}
#endif
`;
}

function shortcutIntentReference(shortcut, intentsByName) {
  if (shortcut.intent && shortcut.intent !== 'CapgoDispatchAppIntent') {
    return `${shortcut.intent}()`;
  }
  const action = escapeSwiftString(shortcut.actionName);
  return `CapgoDispatchAppIntent(actionName: "${action}")`;
}

function generateShortcutsProvider(config) {
  const providerName = config.providerName ?? 'CapgoGeneratedAppShortcuts';
  const blocks = (config.shortcuts ?? [])
    .map((shortcut) => {
      const phrases = shortcut.phrases.map((p) => `          ${phraseToSwiftLiteral(p)},`).join('\n');
      const image = escapeSwiftString(shortcut.systemImageName ?? 'bolt');
      const title = escapeSwiftString(shortcut.shortTitle);
      const intentRef = shortcutIntentReference(shortcut, new Map());
      return `      AppShortcut(
        intent: ${intentRef},
        phrases: [
${phrases}
        ],
        shortTitle: "${title}",
        systemImageName: "${image}"
      ),`;
    })
    .join('\n');

  return `// Generated by @capgo/capacitor-app-intents. Do not edit.
#if canImport(AppIntents)
import AppIntents
import CapgoCapacitorAppIntents

@available(iOS 16.0, *)
struct ${providerName}: AppShortcutsProvider {
  static var appShortcuts: [AppShortcut] {
    [
${blocks}
    ]
  }
}
#endif
`;
}

const args = parseArgs(process.argv);
if (args.help) {
  console.log(
    'Usage: node scripts/generate-typed-intents.mjs --config <file> --output-dir <dir>',
  );
  process.exit(0);
}

const configPath = path.resolve(process.cwd(), args.config);
const outputDir = path.resolve(
  process.cwd(),
  args.outputDir ?? 'CapgoGeneratedAppIntents',
);

const config = loadCodegenConfig(configPath);
fs.mkdirSync(outputDir, { recursive: true });

for (const intent of config.intents ?? []) {
  const file = path.join(outputDir, `${intent.name}.swift`);
  fs.writeFileSync(file, generateIntentSwift(intent), 'utf8');
  console.log(`Wrote ${file}`);
}

if (Array.isArray(config.shortcuts) && config.shortcuts.length > 0) {
  const shortcutsFile = path.join(outputDir, `${config.providerName ?? 'CapgoGeneratedAppShortcuts'}.swift`);
  fs.writeFileSync(shortcutsFile, generateShortcutsProvider(config), 'utf8');
  console.log(`Wrote ${shortcutsFile}`);
}
